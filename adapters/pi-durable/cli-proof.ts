import assert from 'node:assert/strict';
import {mkdtemp, mkdir, writeFile, readFile, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join, resolve} from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {SessionManager} from '@earendil-works/pi-coding-agent';
const repository = fileURLToPath(new URL('../../', import.meta.url));
const binary = resolve(process.env.HSTRY_BIN ?? join(repository, 'target/debug/hstry'));
const directory = await mkdtemp(join(tmpdir(), 'hstry-cli-interop-proof-'));
const config = join(directory, 'config.toml');
const env = {...process.env, HSTRY_NO_SERVICE: '1', XDG_DATA_HOME: join(directory, 'data')};
function run(...args: string[]) {
  const output = spawnSync(binary, ['--config', config, ...args], {env, encoding: 'utf8'});
  assert.equal(output.status, 0, `${args[0]}: ${output.stderr}\n${output.stdout}`);
  const envelope = JSON.parse(output.stdout);
  assert.equal(envelope.ok, true, JSON.stringify(envelope.error));
  return envelope.result;
}
try {
  const snapshots = join(env.XDG_DATA_HOME, 'hstry/pi-durable-snapshots');
  await mkdir(snapshots, {recursive: true});
  const full = JSON.parse(await readFile(fileURLToPath(new URL('./fixtures/full.pi-durable.json', import.meta.url)), 'utf8'));
  await writeFile(join(snapshots, 'first.pi-durable.json'), JSON.stringify(full));
  await writeFile(join(snapshots, 'second.pi-durable.json'), JSON.stringify({...full, storeId: 'other-golden-store'}));
  await writeFile(config, `database = ${JSON.stringify(join(directory, 'db.sqlite'))}\nadapter_paths = [${JSON.stringify(join(repository, 'adapters'))}]\njs_runtime = "bun"\n[service]\nenabled = false\n`);
  const imported = run('import', snapshots, '--adapter', 'pi-durable', '--json');
  assert.equal(imported.conversations, full.conversations.length * 2);
  const indexed = JSON.parse(run('export', '--format', 'json', '--source', 'pi-durable', '--json').content);
  assert.equal(indexed.length, full.conversations.length * 2);
  assert.equal(new Set(indexed.map((conversation: {externalId: string}) => conversation.externalId)).size, indexed.length);
  const roots = indexed.filter((conversation: {metadata: {nativeConversationId: number}}) => conversation.metadata.nativeConversationId === 1);
  assert.equal(roots.length, 2);
  assert.equal(new Set(roots.map((conversation: {metadata: {storeId: string}}) => conversation.metadata.storeId)).size, 2);
  const search = run('search', 'golden-root-archive', '--mode', 'exact', '--limit', '20', '--json');
  const grep = run('search', 'golden-root-archive', '--mode', 'regex', '--limit', '20', '--json');
  const anchors = (result: {hits: {conversation_id: string; message_idx: number}[]}) => result.hits.map(hit => `${hit.conversation_id}:${hit.message_idx}`).sort();
  assert.deepEqual(anchors(search), anchors(grep));
  assert.ok(search.hits.length >= 2);
  const first = search.hits[0];
  const page = run('read', first.conversation_id, '--message-idx', String(first.message_idx), '--json');
  assert.equal(page.records[0].message_idx, first.message_idx);
  assert.match(page.records[0].text, /golden-root-archive/);
  const id = page.records[0].message_id;
  run('import', snapshots, '--adapter', 'pi-durable', '--json');
  const again = run('read', first.conversation_id, '--message-id', id, '--json');
  assert.equal(again.records[0].message_id, id);
  assert.equal(again.records[0].text, page.records[0].text);
  assert.deepEqual(anchors(run('search', 'golden-root-archive', '--mode', 'exact', '--limit', '20', '--json')), anchors(search));
  const exported = run('export', '--format', 'pi', '--conversations', first.conversation_id, '--json');
  const files: {path: string; content: string}[] = exported.files;
  const native = files.find(file => file.path.endsWith('.jsonl'))!;
  const entries = native.content.trim().split('\n').map(line => JSON.parse(line));
  const loaded = SessionManager.inMemory('/synthetic', undefined, entries);
  assert.ok(loaded.getEntries().length);
  const report = JSON.parse(files.find(file => file.path.endsWith('.fidelity.json'))!.content);
  assert.equal(report.disposition, 'detached-continuation');
  assert.equal(report.source.namespace, 'pi-durable');
  assert.ok(report.activationGates.some((gate: {code: string}) => gate.code === 'host-authorization'));
  const beforeFailure = run('export', '--format', 'json', '--source', 'pi-durable', '--json').content;
  await writeFile(join(snapshots, 'unsupported.pi-durable.json'), JSON.stringify({...full, sdkVersion: '9.0.0'}));
  const rejected = spawnSync(binary, ['--config', config, 'import', snapshots, '--adapter', 'pi-durable', '--json'], {env, encoding: 'utf8'});
  assert.notEqual(rejected.status, 0);
  assert.match(rejected.stderr, /Unsupported Durable snapshot/);
  assert.equal(run('export', '--format', 'json', '--source', 'pi-durable', '--json').content, beforeFailure, 'failed validation must not change indexed conversations/messages');
  console.log('PASS: real Rust import, two-store namespace isolation, pre-compaction exact/regex/read anchors, idempotent reimport and existing Pi CLI export parsed by SDK');
} finally {
  if (process.env.HSTRY_KEEP_PROOF === '1') console.log(`Synthetic proof directory: ${directory}`);
  else await rm(directory, {recursive: true, force: true});
}
